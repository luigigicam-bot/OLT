/** Visual adapters only. Existing events own filters, data and authentication. */
const summary = document.getElementById("activeFilterSummary");
const chips = document.getElementById("visualFilterChips");
const search = document.getElementById("searchInput");
const clearButton = document.getElementById("clearFilters");
let lastFilterText = "";

function updateChips() {
  const text = summary.textContent.replace(/^Filtros activos:\s*/, "");
  const query = search.value.trim();
  const signature = `${text}\n${query}`;
  if (lastFilterText === signature) return;
  lastFilterText = signature;
  chips.replaceChildren();
  const values = text ? text.split(" · ") : [];
  if (query) values.push(`Buscar: ${query}`);
  chips.classList.toggle("hidden", !values.length);
  if (!values.length) return;
  const label = document.createElement("span");
  label.className = "active-filters-label";
  label.textContent = "Filtros activos";
  chips.append(label);
  for (const value of values) {
    const chip = document.createElement("span");
    chip.className = "filter-chip";
    chip.textContent = value;
    chips.append(chip);
  }
  const clear = document.createElement("button");
  clear.type = "button";
  clear.className = "text-btn filter-clear";
  clear.textContent = "Limpiar todos";
  clear.addEventListener("click", () => clearButton.click());
  chips.append(clear);
}
new MutationObserver(updateChips).observe(summary, { childList: true, characterData: true, subtree: true });
search.addEventListener("input", updateChips);
clearButton.addEventListener("click", updateChips);
updateChips();

// Day buttons are regenerated by the existing calendar handler. Keep their
// bubbling click inside the popover so the outside-click listener does not
// mistake it for an external click after the button has been detached.
document.getElementById("calendarDays").addEventListener("click", (event) => {
  event.stopPropagation();
});
const calendarDays = document.getElementById("calendarDays");
const readableDate = new Intl.DateTimeFormat("es-PE", { dateStyle: "full", timeZone: "UTC" });
function labelCalendarDays() {
  for (const day of calendarDays.querySelectorAll("[data-calendar-date]")) {
    day.setAttribute("aria-label", readableDate.format(new Date(`${day.dataset.calendarDate}T00:00:00Z`)));
  }
}
new MutationObserver(labelCalendarDays).observe(calendarDays, { childList: true });
labelCalendarDays();

// The return action dispatches the same event as the existing Línea selector.
document.addEventListener("click", (event) => {
  if (!(event.target instanceof Element) || !event.target.closest("[data-reset-line]")) return;
  const filter = document.getElementById("lineFilter");
  filter.value = "";
  filter.dispatchEvent(new Event("change", { bubbles: true }));
});

const tableBody = document.getElementById("tableBody");
const tableHeader = document.getElementById("tableHead");
const loading = document.getElementById("loading");
const tableScroll = tableBody.closest(".sheet-scroll");
const empty = document.createElement("div");
empty.className = "general-empty hidden";
empty.setAttribute("role", "status");
const emptyText = document.createElement("p");
emptyText.textContent = "No hay documentos con estos filtros.";
const emptyClear = document.createElement("button");
emptyClear.type = "button";
emptyClear.className = "btn-secondary";
emptyClear.textContent = "Limpiar filtros";
emptyClear.addEventListener("click", () => clearButton.click());
empty.append(emptyText, emptyClear);
tableScroll.before(empty);
function updateTablePresentation() {
  const noRows = !tableBody.rows.length && loading.classList.contains("hidden");
  empty.classList.toggle("hidden", !noRows);
  tableBody.closest("table").setAttribute("aria-busy", String(!loading.classList.contains("hidden")));
  const headers = [...tableHeader.querySelectorAll("th")];
  for (const th of headers) th.setAttribute("scope", "col");
  for (const input of tableBody.querySelectorAll(".cell-input")) {
    const td = input.closest("td");
    const label = headers[td.cellIndex]?.textContent || input.dataset.key;
    input.setAttribute("aria-label", `${label}, fila ${td.parentElement.firstElementChild.textContent}`);
  }
}
new MutationObserver(updateTablePresentation).observe(tableBody, { childList: true });
new MutationObserver(updateTablePresentation).observe(loading, { attributes: true, attributeFilter: ["class"] });
updateTablePresentation();
