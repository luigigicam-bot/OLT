-- Preserve and reconcile the historical Google Sheets BD source.
-- Canonical OLT rows remain in public.recepcion_olt.
-- Cargo/management fields are projected into olt_control.gestion_olt.
-- The full A:AQ source row is retained in olt_control.bd_import_rows for audit/history.

create table if not exists olt_control.bd_imports (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id),
  archivo text not null,
  archivo_hash text not null,
  pestana text not null default 'BD',
  total_filas integer not null default 0,
  filas_con_cargo integer not null default 0,
  olt_insertados integer not null default 0,
  duplicados integer not null default 0,
  created_at timestamptz not null default now(),
  unique (usuario_id, archivo_hash, pestana)
);

create table if not exists olt_control.bd_import_rows (
  id bigint generated by default as identity primary key,
  import_id bigint not null references olt_control.bd_imports(id) on delete restrict,
  source_row integer not null,
  usuario_id uuid not null references auth.users(id),
  olt_id bigint references public.recepcion_olt(id),

  nro_cargo text,
  fec_cargo date,
  source_fec_vencto date,
  source_indicador text,
  source_estado_cargo text,

  fecha date,
  area text,
  entrega text,
  factura text,
  gr text,
  turno text,
  cita text,
  razon text,
  distrito text,
  provincia text,
  departamento text,
  linea text,
  bultos bigint,
  volumen numeric,
  peso numeric,
  despacho text,
  transporte text,
  mercaderia text,
  observacion text,

  codigo_transporte text,
  placa_prog text,
  dt_prog text,
  transporte_prog text,

  dt text,
  et text,
  placa text,
  fecha_salida_sap date,
  estado_viaje text,
  estado_entrega text,
  fec_reg date,
  hor_reg time,
  usua_ctrl_re text,

  responsable text,
  motivo text,
  source_mes_olt text,
  source_mes_sap text,
  source_retraso text,
  source_dias_plan_salida text,

  business_hash text,
  raw_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (import_id, source_row)
);

create index if not exists bd_import_rows_user_business_idx
  on olt_control.bd_import_rows(usuario_id, business_hash);

create index if not exists bd_import_rows_olt_idx
  on olt_control.bd_import_rows(olt_id);

alter table olt_control.bd_imports enable row level security;
alter table olt_control.bd_import_rows enable row level security;

drop policy if exists "bd_imports_select_own" on olt_control.bd_imports;
create policy "bd_imports_select_own"
on olt_control.bd_imports for select to authenticated
using ((select auth.uid()) = usuario_id);

drop policy if exists "bd_import_rows_select_own" on olt_control.bd_import_rows;
create policy "bd_import_rows_select_own"
on olt_control.bd_import_rows for select to authenticated
using ((select auth.uid()) = usuario_id);

grant select on olt_control.bd_imports to authenticated;
grant select on olt_control.bd_import_rows to authenticated;
